-- Collaboration relay storage (step 15b, D-032).
--
-- The server stores opaque Yjs update bytes and never reads them. note_updates
-- is the ordered log a client replays after its last seen seq; note_snapshots
-- is the compacted state a client can start from, plus the plain text that
-- search, notifications and sync read for a collaborative note.

-- =====================================================================
-- note_updates
-- seq is per note and increasing. The unique (note_id, seq) constraint is also
-- the index every "updates after seq N" query uses, so there is no second index.
-- =====================================================================
CREATE TABLE note_updates (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_id     BIGINT    NOT NULL,
    seq         BIGINT    NOT NULL,
    payload     BYTEA     NOT NULL,
    author_id   BIGINT    NOT NULL,
    created_at  TIMESTAMP NOT NULL,

    CONSTRAINT uq_note_updates_note_seq UNIQUE (note_id, seq)
);

-- =====================================================================
-- note_snapshots
-- One row per collaborative note. Updates up to up_to_seq are folded into state
-- and deleted from note_updates when a snapshot is stored.
-- =====================================================================
CREATE TABLE note_snapshots (
    note_id     BIGINT    PRIMARY KEY,
    state       BYTEA     NOT NULL,
    up_to_seq   BIGINT    NOT NULL,
    plain_text  TEXT,
    updated_at  TIMESTAMP NOT NULL
);

-- =====================================================================
-- notes.body_mode
-- LEGACY: the body is notes.content. COLLAB: the body is the Yjs document, and
-- a note becomes COLLAB when its first update arrives.
-- =====================================================================
ALTER TABLE notes ADD COLUMN body_mode VARCHAR(10) DEFAULT 'LEGACY' NOT NULL;
