-- V1__baseline_schema.sql
--
-- Baseline schema for the whole application, written for Postgres and
-- checked column-by-column against every @Entity in src/main/java. Prod runs
-- hibernate.ddl-auto=validate, which refuses to start if this doesn't match
-- the entities exactly — this migration IS the thing that makes that true on
-- a fresh Neon database.
--
-- Run order: this is the first (and, right now, only) migration. Flyway
-- tracks what's applied in its own flyway_schema_history table, created
-- automatically on first run.
--
-- Assumes an EMPTY database. If you already ran the earlier manual DDL
-- stopgaps (docs/voice_shares_manual_ddl.sql, docs/file_blobs_manual_ddl.sql)
-- against Neon by hand, drop those tables (or recreate the Neon branch)
-- before the first Flyway run — see APPLY_NOTES.md.
--
-- IDENTITY columns use Postgres's native "GENERATED BY DEFAULT AS IDENTITY"
-- (Postgres 10+; Neon runs a current major version), which is what Hibernate
-- 6's PostgreSQLDialect generates for GenerationType.IDENTITY. "BY DEFAULT"
-- rather than "ALWAYS" so an explicit id can still be inserted if ever
-- needed (test fixtures, data migration) without fighting the sequence.


-- =====================================================================
-- users
-- =====================================================================
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name      VARCHAR(255) NOT NULL,
    last_name       VARCHAR(255) NOT NULL,
    username        VARCHAR(255) NOT NULL,
    notarian_id     VARCHAR(255) NOT NULL,
    email           VARCHAR(255) NOT NULL,
    password        VARCHAR(255) NOT NULL,
    user_status     VARCHAR(255),
    email_verified  BOOLEAN      NOT NULL,
    created_at      TIMESTAMP    NOT NULL,
    updated_at      TIMESTAMP,

    CONSTRAINT uq_users_username    UNIQUE (username),
    CONSTRAINT uq_users_notarian_id UNIQUE (notarian_id),
    CONSTRAINT uq_users_email       UNIQUE (email)
);

-- =====================================================================
-- otps
-- =====================================================================
CREATE TABLE otps (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    code_hash   VARCHAR(255) NOT NULL,
    otp_purpose VARCHAR(255) NOT NULL,
    expires_at  TIMESTAMP    NOT NULL,
    attempts    INTEGER      NOT NULL,
    consumed    BOOLEAN      NOT NULL,
    created_at  TIMESTAMP    NOT NULL
);

CREATE INDEX idx_otps_user_id ON otps (user_id);

-- =====================================================================
-- notes
-- =====================================================================
CREATE TABLE notes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id         BIGINT       NOT NULL,
    client_id        VARCHAR(64),
    content          TEXT,
    pinned           BOOLEAN      NOT NULL,
    archived         BOOLEAN      NOT NULL,
    deleted          BOOLEAN      NOT NULL,
    deleted_at       TIMESTAMP,
    version          BIGINT,
    created_at       TIMESTAMP    NOT NULL,
    updated_at       TIMESTAMP,
    last_modified_by BIGINT,

    CONSTRAINT uq_notes_owner_client_id UNIQUE (owner_id, client_id)
);

CREATE INDEX idx_notes_owner_id         ON notes (owner_id);
CREATE INDEX idx_notes_owner_deleted    ON notes (owner_id, deleted);
CREATE INDEX idx_notes_owner_updated_at ON notes (owner_id, updated_at);

-- =====================================================================
-- voice_notes
-- =====================================================================
CREATE TABLE voice_notes (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id           BIGINT       NOT NULL,
    note_id            BIGINT,
    original_filename  VARCHAR(255),
    content_type       VARCHAR(255) NOT NULL,
    storage_key        VARCHAR(255) NOT NULL,
    size_bytes         BIGINT       NOT NULL,
    duration_seconds   INTEGER,
    created_at         TIMESTAMP    NOT NULL,
    updated_at         TIMESTAMP
);

CREATE INDEX idx_voice_notes_owner_id ON voice_notes (owner_id);
CREATE INDEX idx_voice_notes_note_id  ON voice_notes (note_id);

-- =====================================================================
-- transcriptions
-- =====================================================================
CREATE TABLE transcriptions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id       BIGINT       NOT NULL,
    voice_note_id  BIGINT       NOT NULL,
    status         VARCHAR(20)  NOT NULL,
    transcript     TEXT,
    confidence     DOUBLE PRECISION,
    language       VARCHAR(16),
    error_message  TEXT,
    created_at     TIMESTAMP    NOT NULL,
    updated_at     TIMESTAMP,

    CONSTRAINT uq_transcriptions_voice_note_id UNIQUE (voice_note_id)
);

CREATE INDEX idx_transcriptions_owner_id ON transcriptions (owner_id);

-- =====================================================================
-- collaborations
-- =====================================================================
CREATE TABLE collaborations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id         BIGINT      NOT NULL,
    collaborator_id  BIGINT      NOT NULL,
    status           VARCHAR(20) NOT NULL,
    created_at       TIMESTAMP   NOT NULL,
    updated_at       TIMESTAMP,
    last_modified_by BIGINT,

    CONSTRAINT uq_collaborations_owner_collaborator UNIQUE (owner_id, collaborator_id)
);

CREATE INDEX idx_collaborations_collaborator_id ON collaborations (collaborator_id);

-- =====================================================================
-- note_shares
-- =====================================================================
CREATE TABLE note_shares (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_id               BIGINT      NOT NULL,
    owner_id              BIGINT      NOT NULL,
    shared_with_user_id   BIGINT      NOT NULL,
    permission            VARCHAR(20) NOT NULL,
    created_at            TIMESTAMP   NOT NULL,
    updated_at            TIMESTAMP,

    CONSTRAINT uq_note_shares_note_user UNIQUE (note_id, shared_with_user_id)
);

CREATE INDEX idx_note_shares_shared_with_user_id ON note_shares (shared_with_user_id);
CREATE INDEX idx_note_shares_note_id             ON note_shares (note_id);
CREATE INDEX idx_note_shares_owner_shared_with    ON note_shares (owner_id, shared_with_user_id);

-- =====================================================================
-- voice_shares
-- (previously the manual stopgap in docs/voice_shares_manual_ddl.sql —
--  that file is now superseded by this migration; see APPLY_NOTES.md)
-- =====================================================================
CREATE TABLE voice_shares (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voice_note_id         BIGINT      NOT NULL,
    owner_id              BIGINT      NOT NULL,
    shared_with_user_id   BIGINT      NOT NULL,
    permission            VARCHAR(20) NOT NULL,
    created_at            TIMESTAMP   NOT NULL,
    updated_at            TIMESTAMP,

    CONSTRAINT uq_voice_shares_voice_note_user UNIQUE (voice_note_id, shared_with_user_id)
);

CREATE INDEX idx_voice_shares_shared_with_user_id ON voice_shares (shared_with_user_id);
CREATE INDEX idx_voice_shares_voice_note_id       ON voice_shares (voice_note_id);
CREATE INDEX idx_voice_shares_owner_shared_with    ON voice_shares (owner_id, shared_with_user_id);

-- =====================================================================
-- notifications
-- =====================================================================
CREATE TABLE notifications (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id  BIGINT       NOT NULL,
    actor_id      BIGINT,
    type          VARCHAR(50)  NOT NULL,
    target_type   VARCHAR(30),
    target_id     BIGINT,
    target_label  VARCHAR(255),
    read_at       TIMESTAMP,
    created_at    TIMESTAMP    NOT NULL
);

CREATE INDEX idx_notifications_recipient_created ON notifications (recipient_id, created_at);
CREATE INDEX idx_notifications_recipient_read_at ON notifications (recipient_id, read_at);

-- =====================================================================
-- sync_operations
-- =====================================================================
CREATE TABLE sync_operations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        BIGINT       NOT NULL,
    operation_id    VARCHAR(64)  NOT NULL,
    note_id         BIGINT       NOT NULL,
    result_version  BIGINT       NOT NULL,
    created_at      TIMESTAMP    NOT NULL,

    CONSTRAINT uq_sync_operations_owner_operation UNIQUE (owner_id, operation_id)
);

CREATE INDEX idx_sync_operations_created_at ON sync_operations (created_at);

-- =====================================================================
-- note_tombstones
-- =====================================================================
CREATE TABLE note_tombstones (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_id     BIGINT    NOT NULL,
    owner_id    BIGINT    NOT NULL,
    deleted_at  TIMESTAMP NOT NULL
);

CREATE INDEX idx_note_tombstones_owner_deleted_at ON note_tombstones (owner_id, deleted_at);

-- =====================================================================
-- file_blobs
-- Backing table for PostgresFileStorageService (step 1). Folded into the
-- baseline here, as APPLY_NOTES.md for step 1 said it would be — the
-- earlier docs/file_blobs_manual_ddl.sql stopgap is now superseded.
-- =====================================================================
CREATE TABLE file_blobs (
    storage_key   VARCHAR(100) PRIMARY KEY,
    content       BYTEA        NOT NULL,
    content_type  VARCHAR(255),
    size_bytes    BIGINT       NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT now()
);